#!/usr/bin/env python3
"""최종 평가 방식 그대로 학습한다 (설정 하나로 장애물 1/3/5 개를 모두 달림).

11/23 교수님 답변: run 사이에 설정을 바꿀 수 없다 -> 장애물 1, 3, 5 개를 같은 설정 하나로 달려야 한다.
그래서 trial 하나 = 설정 파일(yaml) 하나를 만들고, 장애물 수마다 run_exp.sh eval=1 로 처음부터 한 번씩 달린다.
  - 평가 방식: 자동 복구 없음. 첫 충돌(정지) / maxlaps 바퀴 / dur 초 중 먼저 오는 것에서 끝
  - 주행 중 파라미터를 바꾸는 노드(param_scheduler)를 쓰지 않는다. 설정 파일이 곧 최종 제출 형태
  - 위치는 pf (평가와 같음)

점수 (작을수록 좋음, 평가 순위 = 연속 무충돌 랩 수 순위 + 그 안의 베스트 랩 순위):
  조건마다  count_penalty * (maxlaps - 연속 무충돌 랩)  +  (연속 구간의 베스트 랩, 0랩이면 zero_lap_time)
  를 장애물 1/3/5 에 대해 더한다. count_penalty(20 s) 가 랩타임 차이(1~3 s)보다 훨씬 커서 "안 박기"가 먼저다.

tune_space.yaml 의 키:
  default.<파라미터>          -> 설정 파일의 그 파라미터
  obstacle.guide.speed_scale  -> guide.speed_scale (원래부터 guide 가 기준 경로를 옮긴 곳에서만 쓰이는 값이라
                                  "장애물을 피하는 동안의 속도"와 같다. 노드 안 규칙이라 주행 중 변경이 아님)

결과 (out 폴더):
  <study>.db                 Optuna 기록 (같은 이름으로 다시 실행하면 이어서)
  <study>_trials.csv         trial 별 점수와 조건별 연속 랩/베스트
  <study>_best.yaml          가장 좋은 설정 파일 (그대로 svg_mppi 에 넣어 쓰는 최종 형태)
  <study>_best_params.yaml   그 설정에서 학습한 값만

보통은 train_eval.sh 가 실행한다.
"""
import argparse
import os
import re
import signal
import subprocess
import sys
import time

import optuna
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "analysis"))
from summarize import summarize  # noqa: E402

NODE_PARAM = {"obstacle.guide.speed_scale": "guide.speed_scale"}


def flat_name(key):
    if key in NODE_PARAM:
        return NODE_PARAM[key]
    scope, pname = key.split(".", 1)
    if scope != "default":
        raise ValueError(f"{key}: only default.* (and obstacle.guide.speed_scale) are supported. "
                         "Track-section keys are not allowed (final-eval rule).")
    return pname


def set_param(doc, dotted, value):
    root = doc[next(iter(doc))]["ros__parameters"]
    parts = dotted.split(".")
    d = root
    for p in parts[:-1]:
        d = d.setdefault(p, {})
    d[parts[-1]] = value


def suggest(space, trial):
    params = {}
    if space.get("sectors"):
        raise ValueError("sector (track-section) search spaces are not supported (final-eval rule)")
    for scope in ("default", "obstacle"):
        for k, v in (space.get("fixed", {}).get(scope) or {}).items():
            params[flat_name(f"{scope}.{k}")] = v
    for key, spec in space["space"].items():
        lo, hi = spec[0], spec[1]
        log = len(spec) > 2 and spec[2] == "log"
        if isinstance(lo, int) and isinstance(hi, int):
            v = trial.suggest_int(key, lo, hi, log=log)
        else:
            v = trial.suggest_float(key, float(lo), float(hi), log=log)
        params[flat_name(key)] = v
    return params


def write_cfg(base, params, path):
    doc = yaml.safe_load(open(base))
    for k, v in params.items():
        set_param(doc, k, v)
    with open(path, "w") as f:
        f.write(f"# generated by tune_eval.py from {os.path.basename(base)}\n")
        f.write("# learned: " + ", ".join(f"{k}={v:.4g}" if isinstance(v, float) else f"{k}={v}"
                                          for k, v in sorted(params.items())) + "\n")
        yaml.safe_dump(doc, f, sort_keys=False, allow_unicode=True)


def run_one(a, tag, cfg, obs, seed):
    cmd = ["bash", os.path.join(HERE, "run_exp.sh"), tag, "eval=1", f"maxlaps={a.laps}", f"dur={a.dur}",
           f"obs={obs}", f"seed={seed}", f"nseed={seed}", f"pose={a.pose}", f"params={cfg}"] + a.extra
    p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, start_new_session=True)
    out_dir = None
    try:
        for line in p.stdout:
            m = re.match(r"OUT=(\S+)", line.strip())
            if m:
                out_dir = m.group(1)
            if line.startswith(("stopped:", "laps=", "ERROR")):
                print("    " + line.rstrip(), flush=True)
        p.wait()
    except KeyboardInterrupt:
        os.killpg(p.pid, signal.SIGINT)  # run_exp.sh cleans up its processes on exit
        p.wait()
        raise
    if out_dir is None:  # OUT= is printed at the end; fall back to the newest folder with this tag
        cands = sorted(d for d in os.listdir(a.runs) if d.endswith("_" + tag))
        out_dir = os.path.join(a.runs, cands[-1]) if cands else None
    return out_dir


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--space", required=True)
    ap.add_argument("--base", required=True, help="기본 svg_mppi 설정 yaml (학교 PC: configs/school_orig_t8.yaml)")
    ap.add_argument("--study", default="berlin_eval")
    ap.add_argument("--trials", type=int, default=100)
    ap.add_argument("--obs", default="1 3 5")
    ap.add_argument("--laps", type=int, default=4, help="조건마다 최대 바퀴 (평가는 10, 학습은 시간 때문에 4)")
    ap.add_argument("--dur", type=int, default=0, help="조건마다 최대 초 (0 = laps*25+40)")
    ap.add_argument("--seed", type=int, default=100, help="장애물 seed. 장애물 k 개 조건은 seed+k")
    ap.add_argument("--pose", default="pf")
    ap.add_argument("--count-penalty", type=float, default=20.0)
    ap.add_argument("--zero-lap-time", type=float, default=30.0)
    ap.add_argument("--max-fail", type=int, default=3)
    ap.add_argument("--out", default=os.path.expanduser("~/shared_dir/svg_mppi_exp/tuning"))
    ap.add_argument("--runs", default=os.path.expanduser("~/shared_dir/svg_mppi_exp/runs"))
    ap.add_argument("extra", nargs="*", help="run_exp.sh 에 그대로 넘길 key=value (예: snoise=0.03)")
    a = ap.parse_args()
    a.dur = a.dur or a.laps * 25 + 40
    obs_list = [int(x) for x in a.obs.split()]
    space = yaml.safe_load(open(a.space))
    os.makedirs(a.out, exist_ok=True)
    gen = os.path.join(a.out, f"{a.study}_cfg")
    os.makedirs(gen, exist_ok=True)
    csv_path = os.path.join(a.out, f"{a.study}_trials.csv")
    if not os.path.exists(csv_path):
        with open(csv_path, "w") as f:
            f.write("time,trial,score," + ",".join(f"o{k}_streak,o{k}_best,o{k}_end" for k in obs_list) + ",params\n")

    storage = f"sqlite:///{os.path.join(a.out, a.study + '.db')}"
    study = optuna.create_study(study_name=a.study, storage=storage, load_if_exists=True, direction="minimize")
    study.sampler = optuna.samplers.TPESampler(seed=len(study.trials), n_startup_trials=8)
    if len(study.trials) == 0 and space.get("baseline"):
        study.enqueue_trial(space["baseline"])
    fails = [0]

    def objective(trial):
        params = suggest(space, trial)
        cfg = os.path.join(gen, f"t{trial.number:04d}.yaml")
        write_cfg(a.base, params, cfg)
        print(f"trial {trial.number}: {params}", flush=True)
        score, cols, got_any = 0.0, [], False
        for k in obs_list:
            out_dir = run_one(a, f"te_{a.study}_t{trial.number}_o{k}", cfg, k, a.seed + k)
            r = summarize(out_dir) if out_dir else {}
            streak = r.get("streak")
            if streak is None:  # no race_result json: the run did not start properly
                cols += ["", "", "nodata"]
                score += a.count_penalty * a.laps + a.zero_lap_time
                continue
            got_any = True
            streak = min(streak, a.laps)
            best = r["streak_best"] if streak > 0 else a.zero_lap_time
            score += a.count_penalty * (a.laps - streak) + best
            cols += [str(streak), f"{best:.2f}", r.get("end", "")]
        with open(csv_path, "a") as f:
            f.write(f"{time.strftime('%H:%M:%S')},{trial.number},{score:.2f}," + ",".join(cols) + f",\"{params}\"\n")
        if not got_any:
            fails[0] += 1
            print(f"trial {trial.number}: no run produced results ({fails[0]}/{a.max_fail})", flush=True)
            if fails[0] >= a.max_fail:
                print("too many failed trials -> stopping. check runs/*_te_* logs", flush=True)
                trial.study.stop()
            raise optuna.TrialPruned()
        fails[0] = 0
        print(f"trial {trial.number}: score={score:.2f}  " +
              "  ".join(f"o{k}: {cols[3*i]} laps, best {cols[3*i+1]}" for i, k in enumerate(obs_list)), flush=True)
        return score

    try:
        study.optimize(objective, n_trials=a.trials)
    except KeyboardInterrupt:
        print("interrupted", flush=True)
    done = [t for t in study.trials if t.state == optuna.trial.TrialState.COMPLETE]
    if not done:
        print("no completed trial -> no best config", flush=True)
        sys.exit(1)
    best = study.best_trial
    src = os.path.join(gen, f"t{best.number:04d}.yaml")
    dst = os.path.join(a.out, f"{a.study}_best.yaml")
    params = suggest(space, optuna.trial.FixedTrial(best.params))
    write_cfg(a.base, params, dst)
    with open(os.path.join(a.out, f"{a.study}_best_params.yaml"), "w") as f:
        yaml.safe_dump({"trial": best.number, "score": best.value, "params": params}, f, sort_keys=False)
    print(f"best trial {best.number} score {best.value:.2f} -> {dst} (same as {src})", flush=True)


if __name__ == "__main__":
    main()
